# Generate l10n.h from l10n/windows_translations.json
import json, os, sys
here = os.path.dirname(os.path.abspath(__file__))
data = json.load(open(os.path.join(here, 'windows_translations.json'), encoding='utf-8'))
def c(s):
    return 'L"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'
out = ['// Generated by l10n/gen_l10n.py. Do not edit by hand.', '#pragma once', '#include <wchar.h>',
       'struct L10nLang { const wchar_t *code; const wchar_t *const (*pairs)[2]; int count; };', '']
codes = sorted(data)
for code in codes:
    var = 'L10N_' + code.replace('-', '_')
    out.append('static const wchar_t *const %s[][2] = {' % var)
    for en, t in data[code].items():
        out.append('    {%s, %s},' % (c(en), c(t)))
    out.append('};')
out.append('static const struct L10nLang L10N_LANGS[] = {')
for code in codes:
    var = 'L10N_' + code.replace('-', '_')
    out.append('    {L"%s", %s, (int)(sizeof(%s) / sizeof(%s[0]))},' % (code, var, var, var))
out.append('};')
out.append('#define L10N_LANG_COUNT ((int)(sizeof(L10N_LANGS) / sizeof(L10N_LANGS[0])))')
open(os.path.join(here, '..', 'l10n.h'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print('languages:', len(codes))
